// Lightweight i18n for the Visit Reports module (list + modal). Toggle persists
// in localStorage so it's remembered across visits; default English.
import { useState } from 'react'

const KEY = 'vrLang'

export function useVRLang() {
  const [lang, setLangState] = useState(() => localStorage.getItem(KEY) || 'en')
  const setLang = (l) => { setLangState(l); localStorage.setItem(KEY, l) }
  return [lang, setLang]
}

